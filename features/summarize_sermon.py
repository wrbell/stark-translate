def main():
    parser = argparse.ArgumentParser(
        description="Generate a faithful bilingual session summary or short-session excerpt (local MLX)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    python summarize_sermon.py metrics/ab_metrics_20260208_183356.csv
    python summarize_sermon.py metrics/diarization/sermon.jsonl
    python summarize_sermon.py transcript.csv --model mlx-community/Llama-3.2-3B-Instruct-4bit
    python summarize_sermon.py transcript.jsonl --translate-with-gemma
        """,
    )
    parser.add_argument("input", nargs="+", help="CSV or JSONL transcript file(s)")
    parser.add_argument(
        "--source-lang", choices=("en", "es"), help="Resolve language for legacy records without metadata"
    )
    parser.add_argument(
        "--model", type=str, default=DEFAULT_MODEL, help=f"MLX model for summarization (default: {DEFAULT_MODEL})"
    )
    parser.add_argument(
        "--translate-with-gemma",
        action="store_true",
        help="Use TranslateGemma 4B for Spanish translation instead of the summarization model",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=str,
        default=None,
        help="Output JSON path (default: metrics/sermon_summaries/<input_name>.json)",
    )
    args = parser.parse_args()

    print(f"{'=' * 60}")
    print("  Post-Sermon Summary Generator")
    print(f"  Model: {args.model}")
    print(f"  Input(s): {len(args.input)} file(s)")
    print(f"{'=' * 60}\n")

    # Load and merge all input transcripts
    all_entries = []
    for input_path in args.input:
        print(f"Loading: {input_path}")
        entries = load_transcript(input_path)
        if args.source_lang:
            for entry in entries:
                if entry["source_lang"] and entry["source_lang"] != args.source_lang:
                    parser.error("--source-lang conflicts with the transcript language metadata")
                entry["source_lang"] = args.source_lang
        all_entries.extend(entries)

    if not all_entries:
        print("ERROR: No transcript content found.", file=sys.stderr)
        sys.exit(1)

    total_words = sum(len(e["text"].split()) for e in all_entries)
    print(f"\n  Total: {len(all_entries)} segments, ~{total_words} words")

    # Check for diarization
    diarized = has_diarization(all_entries)
    if total_words < SHORT_SESSION_WORDS:
        print("  Mode: short-session excerpt")
    elif diarized:
        print("  Mode: up to 5 sentences with speaker labels")
    else:
        print("  Mode: up to 3 sentences (no speaker labels)")

    # Build transcript text
    transcript_text = build_transcript_text(all_entries)

    # Generate summary
    print()
    short_session = total_words < SHORT_SESSION_WORDS
    model = tokenizer = None
    if short_session:
        try:
            summary = summarize_short_session(all_entries, args.model)
        except ValueError as exc:
            parser.error(str(exc))
    else:
        model, tokenizer = load_summarization_model(args.model)
        if diarized:
            speaker_texts = get_speaker_texts(all_entries)
            summary = summarize_with_diarization(model, tokenizer, transcript_text, speaker_texts)
        else:
            summary = summarize_without_diarization(model, tokenizer, transcript_text)
        if not summary["english"].strip() or not summary["spanish"].strip():
            parser.error("The model returned an empty summary or translation")

    # Optionally re-translate with TranslateGemma for higher quality
    if args.translate_with_gemma:
        print("\n  Re-translating with TranslateGemma...")
        # Free the summarization model first to save memory
        del model, tokenizer
        import gc

        gc.collect()

        es_translation = translate_with_translategemma(summary["english"])
        summary["spanish"] = es_translation
        summary["translation_method"] = "TranslateGemma-4B"
    elif not short_session:
        summary["translation_method"] = f"{args.model} (direct)"

    # Add metadata
    summary["metadata"] = {
        "input_files": args.input,
        "model": args.model if not short_session or "generated" in summary["translation_method"] else None,
        "timestamp": datetime.now().isoformat(),
        "total_segments": len(all_entries),
        "total_words": total_words,
        "diarized": diarized,
        "source_languages": sorted({e["source_lang"] for e in all_entries if e.get("source_lang")}),
        "content_mode": "excerpt" if short_session else "model_summary",
        "transcript_truncated": len(build_transcript_text(all_entries, max_chars=sys.maxsize)) > MAX_TRANSCRIPT_CHARS,
        "human_reviewed": False,
    }

    # Determine output path
    output_path = args.output
    if output_path is None:
        # Use first input file's name
        input_name = Path(args.input[0]).stem
        output_path = os.path.join(OUTPUT_DIR, f"{input_name}_summary.json")

    # Write output
    write_summary(summary, output_path)

    # Print results
    print(f"\n{'=' * 60}")
    print("  SERMON SUMMARY")
    print(f"{'=' * 60}")
    print(f"\n  English ({summary['format']}):")
    print(f"  {'-' * 40}")
    for line in summary["english"].split("\n"):
        if line.strip():
            print(f"    {line.strip()}")
    print("\n  Spanish:")
    print(f"  {'-' * 40}")
    for line in summary["spanish"].split("\n"):
        if line.strip():
            print(f"    {line.strip()}")
    print(f"\n{'=' * 60}")


if __name__ == "__main__":
    main()
